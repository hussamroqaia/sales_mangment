/**
 * firebase-messaging-sw.js
 *
 * Firebase Cloud Messaging Service Worker — handles background notifications.
 *
 * IMPORTANT: This file lives in public/ and is served as /firebase-messaging-sw.js.
 * It runs in a separate SW context — NOT processed by Vite, so import.meta.env
 * is unavailable here.
 *
 * ─── Configuration strategy (cold-start safe) ─────────────────────────────────
 *
 * Problem: if the user's tab is closed and FCM delivers a push, the browser
 * wakes this SW from a cold start. No Vue page is running, so postMessage from
 * the main thread cannot deliver the Firebase config.
 *
 * Solution: a Vite plugin (see vite.config.js → firebaseSwConfigPlugin) writes
 * public/firebase-config.js at every `npm run dev` and `npm run build` with the
 * resolved env values inlined as `self.FIREBASE_CONFIG = { ... }`.
 *
 * This SW loads that file with importScripts() so it ALWAYS has the config,
 * regardless of whether any tab is open.
 *
 * postMessage is preserved as a secondary path (keeps existing behaviour when
 * the main app sends a refreshed config after re-registration).
 *
 * ─── What this file does NOT do ───────────────────────────────────────────────
 * - Does not contain Firebase Admin / service-account credentials
 * - Does not call getAnalytics
 * - Does not import or initialise anything beyond firebase-app-compat +
 *   firebase-messaging-compat (required by the compat background handler API)
 */

/* global firebase, clients */

importScripts('https://www.gstatic.com/firebasejs/10.12.4/firebase-app-compat.js')
importScripts('https://www.gstatic.com/firebasejs/10.12.4/firebase-messaging-compat.js')

// ─── Primary config source: generated file (cold-start safe) ─────────────────
// firebase-config.js sets self.FIREBASE_CONFIG = { ... }
// It is generated by the Vite plugin at every build/dev-start from .env values.
try {
  importScripts('/firebase-config.js')
} catch (e) {
  console.warn('[SW] Could not load /firebase-config.js — will wait for postMessage config', e.message)
}

// ─── Runtime state ────────────────────────────────────────────────────────────
let _initialized = false

// ─── Initialize Firebase (idempotent) ─────────────────────────────────────────
function tryInitializeFirebase(config) {
  if (_initialized) return
  if (!config || !config.apiKey || !config.projectId) {
    console.warn('[SW] Firebase config missing or incomplete — cannot initialize')

    return
  }

  try {
    if (!firebase.apps.length) {
      firebase.initializeApp(config)
    }

    _initialized = true
    setupBackgroundHandler()
  } catch (error) {
    console.error('[SW] Firebase initialization failed:', error)
  }
}

// ─── Background message handler ───────────────────────────────────────────────
function setupBackgroundHandler() {
  const messaging = firebase.messaging()

  // Called when FCM delivers a push while the app tab is closed/backgrounded.
  messaging.onBackgroundMessage(payload => {
    console.info('[SW] Background message received')

    const notificationTitle = payload.notification?.title
      || payload.data?.title
      || 'New Notification'

    const notificationBody = payload.notification?.body
      || payload.data?.body
      || ''

    const notificationIcon = payload.notification?.icon
      || payload.data?.icon
      || '/favicon.ico'

    const notificationData = {
      url: payload.data?.actionUrl || payload.data?.url || '/',
      ...payload.data,
    }

    self.registration.showNotification(notificationTitle, {
      body: notificationBody,
      icon: notificationIcon,
      badge: '/favicon.ico',
      data: notificationData,
      // Deduplicate: same notificationId or same title won't stack
      tag: payload.data?.notificationId || notificationTitle,
    })
  })
}

// ─── Auto-initialize from the generated config file ───────────────────────────
// self.FIREBASE_CONFIG is set by importScripts('/firebase-config.js') above.
// Try immediately so cold-start pushes work without any postMessage needed.
if (typeof self.FIREBASE_CONFIG !== 'undefined') {
  tryInitializeFirebase(self.FIREBASE_CONFIG)
}

// ─── Secondary: receive config from main thread (postMessage fallback) ─────────
// The main app sends the config after SW registration. This path handles:
//   - First install before firebase-config.js was generated
//   - Config updates between deploys (new postMessage overrides stale file)
self.addEventListener('message', event => {
  if (event.data?.type === 'FIREBASE_CONFIG') {
    // If already initialized with the same project, skip re-init
    if (_initialized) return
    tryInitializeFirebase(event.data.config)
  }
})

// ─── Notification click handler ───────────────────────────────────────────────
self.addEventListener('notificationclick', event => {
  event.notification.close()

  const notificationData = event.notification.data || {}

  // Only navigate to URLs explicitly provided by the backend payload.
  // Do NOT invent routes from notification types.
  const targetUrl = notificationData.url || notificationData.actionUrl || '/'

  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then(windowClients => {
      // Focus an existing app window if one is open
      const appOrigin = self.location.origin
      const existingWindow = windowClients.find(client => {
        return client.url.startsWith(appOrigin)
      })

      if (existingWindow) {
        existingWindow.focus()

        if (targetUrl && targetUrl !== '/') {
          try {
            existingWindow.navigate(targetUrl)
          } catch {
            // navigate() not available in all browsers — ignore
          }
        }

        return existingWindow
      }

      if (clients.openWindow) {
        return clients.openWindow(targetUrl)
      }
    }),
  )
})

// ─── Service worker activate ──────────────────────────────────────────────────
self.addEventListener('activate', event => {
  event.waitUntil(clients.claim())
})
